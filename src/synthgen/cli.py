BANNER = "SYNTHETIC TEST DATA - NOT REAL PEOPLE, ACCOUNTS OR BUREAU RECORDS. Placeholder schema and codes (U6)."


def _dump_jsonl(path: Path, rows: list[dict]) -> str:
    text = "".join(json.dumps(r, sort_keys=True, ensure_ascii=False) + "\n" for r in rows)
    path.write_text(text, encoding="utf-8")
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def summarise(labels: list[dict]) -> dict:
    n = len(labels)
    edge = [l for l in labels if set(l["edge_tags"]) & EDGE_TAGS]
    adv = [l for l in labels if set(l["adversarial_tags"]) & ADVERSARIAL_TAGS]
    return {
        "n_cases": n,
        "edge_case_count": len(edge), "edge_case_share": round(len(edge) / n, 4) if n else 0,
        "adversarial_count": len(adv), "adversarial_share": round(len(adv) / n, 4) if n else 0,
        "outcomes": dict(sorted(collections.Counter(l["gold"]["outcome"] for l in labels).items())),
        "escalation_reasons": dict(sorted(collections.Counter(r for l in labels for r in l["gold"]["escalation_reasons"]).items())),
        "edge_tags": dict(sorted(collections.Counter(t for l in labels for t in l["edge_tags"]).items())),
        "adversarial_tags": dict(sorted(collections.Counter(t for l in labels for t in l["adversarial_tags"]).items())),
        "categories": dict(sorted(collections.Counter("+".join(l["categories"]) for l in labels).items())),
        "claims_total": sum(len(l["claims"]) for l in labels),
    }


def write_set(out: Path, seed: int, data: dict) -> dict:
    out.mkdir(parents=True, exist_ok=True)
    hashes = {
        "acdvs.jsonl": _dump_jsonl(out / "acdvs.jsonl", data["acdvs"]),
        "sor_accounts.jsonl": _dump_jsonl(out / "sor_accounts.jsonl", data["accounts"]),
        "labels.jsonl": _dump_jsonl(out / "labels.jsonl", data["labels"]),
    }
    manifest = {
        "synthetic": True, "banner": BANNER, "seed": seed,
        "generator_version": GENERATOR_VERSION, "fixture_schema_version": FIXTURE_SCHEMA_VERSION,
        "reference_tables": tables.table_versions(), "files_sha256": hashes,
        "summary": summarise(data["labels"]),
    }
    (out / "manifest.json").write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return manifest


