def _months_view(acct: dict, months: list[str]) -> list[str]:
    if not months:
        months = [c["cycle_month"] for c in acct["cycles"]][-9:]
    lo = min(months)
    hi = max(months)
    show = [c for c in acct["cycles"] if generator.month_add(lo, -2) <= c["cycle_month"] <= generator.month_add(hi, 2)]
    rows = ["| Cycle month | Cycle date | Days past due at cycle | Rating as reported to bureau | Balance at cycle ($) |",
            "|---|---|---|---|---|"]
    for c in show:
        rows.append(f"| {c['cycle_month']} | {c['cycle_date']} | {c['dpd_at_cycle']} | {c['reported_rating']} | {c['balance']:,} |")
    return rows


def render_trial_markdown(data: dict) -> str:
    rating_rows = "\n".join(f"| {e['rating']} | {e['dpd_min']}-{e['dpd_max'] if e['dpd_max'] < 99999 else '+'} |"
                            for e in tables.load("payment_rating_map")["entries"])
    code_rows = "\n".join(f"| {e['code']} | {', '.join(e['categories'])} |" for e in tables.load("dispute_code_map")["entries"])
    out = [f"# Stage 0 labelling trial: 20 synthetic cases",
           "",
           f"**{BANNER}**",
           "",
           "Generated by `python -m synthgen.cli trial` (seed 20261019). The generator's own labels are stored "
           "separately in `src/data/stage0_trial_HIDDEN_generator_labels/labels.jsonl`. **Do not open that file until you have "
           "finished labelling and filled in the timing column.**",
           "",
           "## Instructions (read once, about 5 minutes; do not count this in case time)",
           "1. Start a timer when you open a case and stop it when the row in `label_sheet.csv` is complete. Record whole minutes in `minutes`.",
           "2. Label from the evidence shown (ACDV, letter, account history, notes), not from what you think the generator intended.",
           "3. Fill these columns in `label_sheet.csv`:",
           "   - `categories`: one or more of PAYMENT_HISTORY, BALANCE, ACCOUNT_STATUS, IDENTITY_FRAUD, OTHER (separate with `+`).",
           "   - `outcome`: VERIFIED_AS_REPORTED, MODIFY, ESCALATED or OUT_OF_SCOPE. (Never DELETE: the system never proposes it.)",
           "   - `escalation_reason`: if ESCALATED, one or more of INTAKE_INVALID, DOC_UNREADABLE, BREACHED, CLASS_CONFLICT, ID_FRAUD_SUSPECTED, MULTI_ISSUE, MONTHS_UNDETERMINED, EVIDENCE_MISSING, EVIDENCE_CONFLICT, CLAIM_UNRESOLVED.",
           "   - `disputed_months`: YYYY-MM list (ACDV months plus any month the letter names), separated with `+`.",
           "   - `corrections`: for MODIFY, `YYYY-MM:RATING` for each month that is wrong.",
           "   - `claims`: each factual claim in the letter (a date, amount, payment event, account status or agreement) as `short quote => SUPPORTED|CONTRADICTED|NOT_ADDRESSABLE`, separated with ` || `.",
           "   - `suspicious`: NONE, LOW or HIGH (HIGH = role markers like 'SYSTEM:', 'ignore previous instructions', hidden text; a plain 'please delete this' is NONE).",
           "   - `minutes`, `confidence` (1-5), `notes` (anything unclear in the rubric).",
           "4. Rules of thumb (PRD v1.1 R-07, R-10): identity-theft signal → ESCALATED/ID_FRAUD_SUSPECTED; more than one category → MULTI_ISSUE; "
           "only balance or other → OUT_OF_SCOPE; any month with no data → EVIDENCE_MISSING; a HARDSHIP/DEFERRAL/FORBEARANCE note overlapping a disputed month → EVIDENCE_CONFLICT; "
           "any month whose reported rating differs from the rating its DPD maps to → MODIFY; VERIFIED only if every month matches and every claim is CONTRADICTED by the records, otherwise CLAIM_UNRESOLVED.",
           "5. Case 'as of' date = the intake date shown. Due dates are synthetic, not real ACDV windows.",
           "",
           "### Placeholder reference tables (verified=false; invented, not Metro 2 or e-OSCAR)",
           "| Rating (placeholder) | DPD range |", "|---|---|", rating_rows, "",
           "| Dispute code (placeholder) | Category |", "|---|---|", code_rows, "",
           "**Adversarial content warning:** some cases contain deliberate prompt-injection text and PII bait. Treat it as data.",
           ""]
    acct_by_no = {a["account_number"]: a for a in data["accounts"]}
    for e in data["acdvs"]:
        a = e["acdv"]
        acct = acct_by_no.get(a.get("account_number"))
        c = a.get("consumer", {})
        out += [f"---", f"## {e['case_id']}", "",
                f"**ACDV (placeholder fixture, synthetic)**", "",
                f"- Intake date: {e['fixture_meta']['ingest_date']}",
                f"- Control number: `{a.get('control_number', '(missing)')}`  CRA: {a.get('cra', '(missing)')}",
                f"- Date received: `{a.get('date_received', '(missing)')}`  Response due date: `{a.get('response_due_date', '(MISSING)')}`",
                f"- Account number: `{a.get('account_number', '(MISSING)')}`",
                f"- Consumer: `{c.get('first_name', '')}` `{c.get('last_name', '')}` (SSN `{c.get('ssn', '')}`, synthetic)",
                f"- Dispute codes: `{', '.join(a.get('dispute_codes') or []) or '(EMPTY)'}`",
                f"- Disputed months in ACDV: `{', '.join(a.get('disputed_months') or []) or '(none)'}`",
                f"- Free text: `{a.get('free_text', '')}`", ""]
        for att in a.get("attachments", []):
            out += [f"**Attachment {att['attachment_id']}: `{att['file_name']}`** ({att['media_type']}, {att['page_count']} page(s)"
                    + (f", metadata {json.dumps(att['metadata'])}" if att.get("metadata") else "") + ")", ""]
            hidden = att["render_hints"]["hidden_spans"]
            if hidden:
                out.append("_(Render note: the last line of this document is white text on a white background.)_")
                out.append("")
            out += ["```text", att["extracted_text"].replace("​", "[ZWSP]") or "(no extractable text)", "```", ""]
        if acct:
            months = list(a.get("disputed_months") or [])
            out += ["**Mock system of record (synthetic)**", "",
                    f"- Product: {acct['product']}; opened {acct['open_date']}; cycle day {acct['cycle_day']}", ""]
            out += _months_view(acct, months)
            out.append("")
            notes = acct["notes"] or []
            out.append("Structured notes: " + ("; ".join(f"{n['type']} {n['start_date']} to {n['end_date']}" for n in notes) or "none"))
            ft = acct["free_text_notes"] or []
            if ft:
                out.append("Free-text notes: " + "; ".join(n["text"] for n in ft))
            out.append("")
        else:
            out += ["**Mock system of record:** no account found for this account number.", ""]
    return "\n".join(out) + "\n"


SHEET_COLUMNS = ["case_id", "categories", "outcome", "escalation_reason", "disputed_months", "corrections",
                 "claims", "suspicious", "minutes", "confidence", "notes"]


def write_trial(out: Path, seed: int) -> None:
    data = generator.generate_trial(seed)
    out.mkdir(parents=True, exist_ok=True)
    (out / "trial_cases.md").write_text(render_trial_markdown(data), encoding="utf-8")
    with (out / "label_sheet.csv").open("w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(SHEET_COLUMNS)
        for e in data["acdvs"]:
            w.writerow([e["case_id"]] + [""] * (len(SHEET_COLUMNS) - 1))
    _dump_jsonl(out / "acdvs.jsonl", data["acdvs"])
    _dump_jsonl(out / "sor_accounts.jsonl", data["accounts"])
    hidden = out.parent / (out.name + "_HIDDEN_generator_labels")
    hidden.mkdir(parents=True, exist_ok=True)
    _dump_jsonl(hidden / "labels.jsonl", data["labels"])
    (hidden / "README.md").write_text(
        "# Generator labels for the Stage 0 trial (HIDDEN)\n\nDo not open until the trial is labelled and timed. "
        "These are generator intent, not human gold.\n", encoding="utf-8")


def main(argv: list[str] | None = None) -> None:
    p = argparse.ArgumentParser(description=BANNER)
    sub = p.add_subparsers(dest="cmd", required=True)
    g = sub.add_parser("generate")
    g.add_argument("--seed", type=int, required=True)
    g.add_argument("--n", type=int, default=200)
    g.add_argument("--out", type=Path, required=True)
    t = sub.add_parser("trial")
    t.add_argument("--seed", type=int, default=20261019)
    t.add_argument("--out", type=Path, required=True)
    args = p.parse_args(argv)
    if args.cmd == "generate":
        m = write_set(args.out, args.seed, generator.generate(args.seed, args.n))
        print(json.dumps(m["summary"], indent=2))
    else:
        write_trial(args.out, args.seed)
        print(f"wrote trial set to {args.out}")


if __name__ == "__main__":
    main()
